CREATE TABLE user_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT NOT NULL REFERENCES users(id),
    following_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_user_follows_pair UNIQUE (follower_id, following_id),
    CONSTRAINT ck_user_follows_not_self CHECK (follower_id <> following_id),
    CONSTRAINT ck_user_follows_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT ck_user_follows_accepted_at CHECK (
        (status = 'PENDING' AND accepted_at IS NULL)
        OR (status = 'ACCEPTED' AND accepted_at IS NOT NULL)
    )
);
CREATE INDEX ix_user_follows_following_status
    ON user_follows (following_id, status);

CREATE INDEX ix_user_follows_follower_status
    ON user_follows (follower_id, status);