CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    follow_id BIGINT REFERENCES user_follows(id) ON DELETE SET NULL,
    type VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_user_notifications_not_self CHECK (recipient_id <> actor_id),
    CONSTRAINT ck_user_notifications_type CHECK (
        type IN ('FOLLOW_REQUEST', 'NEW_FOLLOWER', 'FOLLOW_ACCEPTED')
    )
);

CREATE INDEX ix_user_notifications_recipient_occurred
    ON user_notifications (recipient_id, occurred_at DESC, id DESC);

CREATE INDEX ix_user_notifications_unread
    ON user_notifications (recipient_id)
    WHERE read_at IS NULL;

CREATE INDEX ix_user_notifications_follow_type
    ON user_notifications (follow_id, type)
    WHERE follow_id IS NOT NULL;