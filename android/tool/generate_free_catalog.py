"""Generate small Dart metadata only; book contents are never in the catalogue."""
import json
from pathlib import Path
from verify_collection import count
assert count>=7
def dart(value): return json.dumps(value,ensure_ascii=False).replace('$','\\$')
lines=["part of 'free_work.dart';",'', '// Generated by tool/generate_free_catalog.py from reviewed provenance manifests.', 'const preparedFreeWorks = <FreeWork>[']
for path in sorted(Path('assets/free_works').glob('*.source.json')):
 m=json.loads(path.read_text(encoding='utf-8'))
 if not m.get('complete'): continue
 assert m['reviewed_complete']
 lines.append('  FreeWork(')
 values=dict(id=m['id'],title=m['title'],author=m['author'],language='es',source=m['source'],edition=m['edition'],conditions=m['license']+'. Texto de la edición indicada; se conserva la transcripción y su ortografía, con posibles erratas. Créditos, revisiones e historiales al final del texto. '+m['license_url'],genre=m['genre'],assetPath='assets/free_works/'+m['slug']+'.txt')
 for k,v in values.items(): lines.append('    '+k+': '+dart(v)+',')
 lines+=['    isComplete: true,','  ),']
lines+= ['];','']
Path('lib/features/gutendex/models/prepared_free_works.dart').write_text('\n'.join(lines),encoding='utf-8')
print('Generated',len(list(Path('assets/free_works').glob('*.txt'))),'local works')
