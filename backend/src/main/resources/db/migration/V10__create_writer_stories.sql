-- Writer-only aggregate; metadata and ordered chapter JSON commit atomically.
CREATE TABLE writer_stories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 story_key VARCHAR(64) NOT NULL UNIQUE,
 owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 payload TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 revision BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_writer_stories_owner_updated ON writer_stories(owner_id, updated_at);
