    CONSTRAINT ck_chapter_comment_report_status CHECK (status IN ('PENDING', 'RESOLVED', 'DISMISSED'))
);
CREATE INDEX ix_chapter_comment_reports_user ON chapter_comment_reports(user_id);

-- A rating may exist without review text. Visibility is independent of identity.
CREATE TABLE book_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL,
    review_text VARCHAR(500),
    visibility VARCHAR(16) NOT NULL DEFAULT 'PUBLIC',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_book_reviews_user UNIQUE (book_id, user_id),
    CONSTRAINT ck_book_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_book_reviews_visibility CHECK (visibility IN ('PUBLIC', 'ANONYMOUS', 'PRIVATE'))
);
CREATE INDEX ix_book_reviews_user ON book_reviews(user_id);

