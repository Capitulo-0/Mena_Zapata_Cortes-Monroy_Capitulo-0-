CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(30) NOT NULL,
    granted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role),
    CONSTRAINT ck_user_roles_role CHECK (role IN ('ADMIN'))
);

CREATE TABLE organizer_verification_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    representative_name VARCHAR(150) NOT NULL,
    organization_name VARCHAR(200) NOT NULL,
    organization_rut VARCHAR(20),
    city VARCHAR(120) NOT NULL,
    public_address VARCHAR(300),
    contact_email VARCHAR(320) NOT NULL,
    contact_phone VARCHAR(40) NOT NULL,
    social_url VARCHAR(2048),
    organization_description VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT REFERENCES users(id),
    review_reason VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_organizer_verification_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_organizer_verification_representative
        CHECK (TRIM(representative_name) <> ''),
    CONSTRAINT ck_organizer_verification_organization
        CHECK (TRIM(organization_name) <> ''),
    CONSTRAINT ck_organizer_verification_city
        CHECK (TRIM(city) <> ''),
    CONSTRAINT ck_organizer_verification_email
        CHECK (TRIM(contact_email) <> ''),
    CONSTRAINT ck_organizer_verification_phone
        CHECK (TRIM(contact_phone) <> ''),
    CONSTRAINT ck_organizer_verification_description
        CHECK (TRIM(organization_description) <> ''),
    CONSTRAINT ck_organizer_verification_review
        CHECK (
            (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
            OR
            (status IN ('APPROVED', 'REJECTED')
                AND reviewed_by IS NOT NULL
                AND reviewed_at IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uq_organizer_verification_pending
    ON organizer_verification_requests (user_id)
    WHERE status = 'PENDING';

CREATE UNIQUE INDEX uq_organizer_verification_approved
    ON organizer_verification_requests (user_id)
    WHERE status = 'APPROVED';

CREATE INDEX ix_organizer_verification_status_created
    ON organizer_verification_requests (status, created_at DESC);

CREATE INDEX ix_organizer_verification_user_created
    ON organizer_verification_requests (user_id, created_at DESC);