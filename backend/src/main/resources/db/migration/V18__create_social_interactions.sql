CREATE TABLE book_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id BIGINT,
    content TEXT NOT NULL,
    anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_book_comments_scope UNIQUE (id, book_id),
    CONSTRAINT fk_book_comments_parent FOREIGN KEY (parent_id, book_id)
        REFERENCES book_comments(id, book_id) ON DELETE CASCADE,
    CONSTRAINT ck_book_comments_content CHECK (CHAR_LENGTH(TRIM(content)) BETWEEN 1 AND 300),
    CONSTRAINT ck_book_comments_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX ix_book_comments_scope ON book_comments(book_id, created_at);
CREATE INDEX ix_book_comments_parent ON book_comments(parent_id);
CREATE INDEX ix_book_comments_user ON book_comments(user_id);

CREATE TABLE book_comment_likes (
    comment_id BIGINT NOT NULL REFERENCES book_comments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (comment_id, user_id)
);
CREATE INDEX ix_book_comment_likes_user ON book_comment_likes(user_id);

CREATE TABLE book_comment_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES book_comments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_book_comment_reports UNIQUE (comment_id, user_id),
    CONSTRAINT ck_book_comment_report_reason CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 500),
    CONSTRAINT ck_book_comment_report_status CHECK (status IN ('PENDING', 'RESOLVED', 'DISMISSED'))
);
CREATE INDEX ix_book_comment_reports_user ON book_comment_reports(user_id);

CREATE TABLE chapter_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    story_key VARCHAR(64) NOT NULL REFERENCES writer_stories(story_key) ON DELETE CASCADE,
    chapter_id VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id BIGINT,
    content TEXT NOT NULL,
    anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_chapter_comments_scope UNIQUE (id, story_key, chapter_id),
    CONSTRAINT fk_chapter_comments_parent FOREIGN KEY (parent_id, story_key, chapter_id)
        REFERENCES chapter_comments(id, story_key, chapter_id) ON DELETE CASCADE,
    CONSTRAINT ck_chapter_comments_content CHECK (CHAR_LENGTH(TRIM(content)) BETWEEN 1 AND 220),
    CONSTRAINT ck_chapter_comments_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX ix_chapter_comments_scope ON chapter_comments(story_key, chapter_id, created_at);
CREATE INDEX ix_chapter_comments_parent ON chapter_comments(parent_id);
CREATE INDEX ix_chapter_comments_user ON chapter_comments(user_id);

CREATE TABLE chapter_comment_likes (
    comment_id BIGINT NOT NULL REFERENCES chapter_comments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (comment_id, user_id)
