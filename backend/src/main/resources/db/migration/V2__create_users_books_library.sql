CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    display_name VARCHAR(120),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email CHECK (TRIM(email) <> '' AND email = LOWER(TRIM(email)))
);
CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    author VARCHAR(300),
    synopsis TEXT,
    isbn VARCHAR(32),
    publisher VARCHAR(300),
    total_pages INTEGER,
    publication_year INTEGER,
    cover_url VARCHAR(2048),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_books_title CHECK (TRIM(title) <> ''),
    CONSTRAINT ck_books_pages CHECK (total_pages IS NULL OR total_pages > 0),
    CONSTRAINT ck_books_year CHECK (publication_year IS NULL OR publication_year > 0)
);
CREATE TABLE library_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    book_id BIGINT NOT NULL REFERENCES books(id),
    status VARCHAR(20) NOT NULL,
    reading_format VARCHAR(20) NOT NULL,
    current_page INTEGER NOT NULL DEFAULT 0,
    total_pages INTEGER,
    publisher_override VARCHAR(300),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_library_user_book UNIQUE (user_id, book_id),
    CONSTRAINT ck_library_status CHECK (status IN ('POR_LEER', 'LEYENDO', 'LEIDO')),
    CONSTRAINT ck_library_format CHECK (reading_format IN ('FISICO', 'EBOOK', 'OTRA_PLATAFORMA')),
    CONSTRAINT ck_library_pages CHECK (current_page >= 0 AND (total_pages IS NULL OR (total_pages > 0 AND current_page <= total_pages))),
    CONSTRAINT ck_library_unread CHECK (status <> 'POR_LEER' OR current_page = 0),
    CONSTRAINT ck_library_read CHECK (status <> 'LEIDO' OR total_pages IS NULL OR current_page = total_pages)
);
CREATE INDEX ix_library_book ON library_entries(book_id);
