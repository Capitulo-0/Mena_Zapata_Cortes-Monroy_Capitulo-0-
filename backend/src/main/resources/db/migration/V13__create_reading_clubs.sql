CREATE TABLE reading_clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    meeting_date DATE NOT NULL,
    meeting_time TIME WITHOUT TIME ZONE NOT NULL,
    modality VARCHAR(20) NOT NULL,
    meeting_place VARCHAR(300),
    instagram VARCHAR(200),
    facebook VARCHAR(200),
    x_handle VARCHAR(200),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reading_clubs_name CHECK (TRIM(name) <> ''),
    CONSTRAINT ck_reading_clubs_description CHECK (TRIM(description) <> ''),
    CONSTRAINT ck_reading_clubs_modality CHECK (modality IN ('ONLINE', 'PRESENCIAL')),
    CONSTRAINT ck_reading_clubs_place CHECK (
        modality <> 'PRESENCIAL'
        OR (meeting_place IS NOT NULL AND TRIM(meeting_place) <> '')
    ),
    CONSTRAINT ck_reading_clubs_status CHECK (status IN ('ACTIVE', 'CLOSED'))
);

CREATE INDEX ix_reading_clubs_organizer ON reading_clubs (organizer_user_id);
CREATE INDEX ix_reading_clubs_status_created ON reading_clubs (status, created_at DESC);

CREATE TABLE club_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES reading_clubs(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_club_memberships_club_user UNIQUE (club_id, user_id)
);

CREATE INDEX ix_club_memberships_user ON club_memberships (user_id);
